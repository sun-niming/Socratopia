md = md_path.read_text(encoding="utf-8")
lines = md.splitlines()

row_re = re.compile(r"^\| \[(.+?)\]\((https://[^)]+)\) \| (.+?) \|$")
out, matched, seen = [], 0, set()
for ln in lines:
    m = row_re.match(ln)
    if m:
        title, url, rest = m.groups()
        parts = [p.strip() for p in rest.split(" | ")]
        # 与列数无关：版本永远取最后一个字段，体裁一律以 G 为准。
        # （早期版本按 len==3/2 分支，遇到被污染的 5 列行会静默错位。）
